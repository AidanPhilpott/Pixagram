//! Preset store — named, editable bundles of the shared `Adjustments` stack.
//!
//! Phase 3, model (A): a preset IS a saved `Adjustments` value plus a name —
//! the same slider vocabulary as the editor, no second color stage. Each user
//! preset lives as one pretty-printed JSON file under `<app-data>/presets/`
//! so the library is portable, diffable, and syncable. Built-in presets are
//! defined in code, flagged `builtin: true`, and can't be deleted, renamed,
//! or shadowed by a user preset.
//!
//! Every store function takes the preset directory explicitly (the Tauri
//! commands in `lib.rs` resolve it from the app-data path) so unit tests can
//! point the store at a temp dir and never touch real app data.
//!
//! Forward compatibility comes for free from constraint #1's carry-forward:
//! `Adjustments` keeps `#[serde(default)]` on every field, so preset JSON
//! written before a new slider existed still deserializes.

use std::fs;
use std::path::Path;

use anyhow::{bail, Context};
use serde::{Deserialize, Serialize};
use ts_rs::TS;

use crate::adjustments::{Adjustments, CurvePoint};

/// Bump when the preset *file layout* changes (name/version/adjustments keys).
/// Growing `Adjustments` itself does NOT need a bump — serde defaults cover it.
const PRESET_VERSION: u32 = 1;

/// Longest accepted preset name (UI sanity, and keeps file names reasonable).
const MAX_NAME_LEN: usize = 64;

/// One preset as the frontend sees it. The TS mirror is generated by ts-rs
/// (same mechanism as `Adjustments` — regenerate with `npm run gen:types`).
#[derive(Debug, Clone, Serialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export, export_to = "../../src/adjustments/generated/")]
pub struct Preset {
    pub name: String,
    /// Built-ins ship with the app and can't be deleted or renamed.
    pub builtin: bool,
    pub adjustments: Adjustments,
}

/// On-disk layout of one user-preset JSON file.
#[derive(Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
struct PresetFile {
    version: u32,
    name: String,
    #[serde(default)]
    adjustments: Adjustments,
}

/// The presets that ship with the app. Defined in code (not files) so they're
/// always present, versioned with the app, and immune to store corruption.
pub fn builtin_presets() -> Vec<Preset> {
    let builtin = |name: &str, adjustments: Adjustments| Preset {
        name: name.to_string(),
        builtin: true,
        adjustments,
    };
    vec![
        // The do-nothing baseline — applying it resets a photo to defaults.
        builtin("Neutral", Adjustments::default()),
        // More pop: an S-curve plus vibrance, anchored by slightly deeper blacks.
        builtin(
            "Punchy",
            Adjustments {
                contrast: 0.25,
                vibrance: 0.3,
                blacks: -0.1,
                ..Default::default()
            },
        ),
        // Faded-film look: soft contrast, recovered highlights, lifted shadows,
        // muted color, a touch of warmth, and a gently faded tone curve.
        builtin(
            "Soft Film",
            Adjustments {
                contrast: -0.15,
                highlights: -0.3,
                shadows: 0.25,
                saturation: -0.2,
                temperature: 0.08,
                curve: vec![
                    CurvePoint { x: 0.0, y: 0.04 },
                    CurvePoint { x: 1.0, y: 0.97 },
                ],
                ..Default::default()
            },
        ),
        // Full desaturation with punched-up tone — a high-contrast B&W look.
        builtin(
            "Mono Contrast",
            Adjustments {
                saturation: -1.0,
                contrast: 0.35,
                whites: 0.1,
                blacks: -0.15,
                ..Default::default()
            },
        ),
    ]
}

/// True when `name` collides with a built-in (case-insensitive, trimmed).
fn is_builtin_name(name: &str) -> bool {
    let name = name.trim();
    builtin_presets()
        .iter()
        .any(|p| p.name.eq_ignore_ascii_case(name))
}

/// Validate a user-preset name; returns the trimmed display name.
fn validate_name(name: &str) -> anyhow::Result<String> {
    let name = name.trim();
    if name.is_empty() {
        bail!("preset name can't be empty");
    }
    if name.chars().count() > MAX_NAME_LEN {
        bail!("preset name is too long (max {MAX_NAME_LEN} characters)");
    }
    if is_builtin_name(name) {
        bail!("\"{name}\" is a built-in preset");
    }
    Ok(name.to_string())
}

/// Map a preset name to its JSON file name. Anything the filesystem might
/// object to becomes `_`, which also forecloses path traversal via the name.
fn file_name_for(name: &str) -> String {
    let safe: String = name
        .trim()
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || matches!(c, '-' | '_' | ' ') {
                c
            } else {
                '_'
            }
        })
        .collect();
    format!("{safe}.json")
}

/// Read one user-preset file. The display name comes from the JSON `name`
/// field (the file name is just a sanitized derivative of it).
fn read_preset_file(path: &Path) -> anyhow::Result<Preset> {
    let text = fs::read_to_string(path)
        .with_context(|| format!("reading {}", path.display()))?;
    let file: PresetFile = serde_json::from_str(&text)
        .with_context(|| format!("parsing {}", path.display()))?;
    Ok(Preset {
        name: file.name,
        builtin: false,
        adjustments: file.adjustments,
    })
}

/// List every preset: built-ins first (fixed order), then user presets sorted
/// by name. Unreadable preset files are skipped with a warning, not fatal.
pub fn list_presets(dir: &Path) -> anyhow::Result<Vec<Preset>> {
    let mut out = builtin_presets();
    let mut user = Vec::new();
    if dir.is_dir() {
        for entry in fs::read_dir(dir).with_context(|| format!("listing {}", dir.display()))? {
            let path = entry?.path();
            let is_json = path
                .extension()
                .and_then(|e| e.to_str())
                .is_some_and(|e| e.eq_ignore_ascii_case("json"));
            if !is_json {
                continue;
            }
            match read_preset_file(&path) {
                Ok(p) => user.push(p),
                Err(e) => log::warn!("skipping unreadable preset {}: {e:#}", path.display()),
            }
        }
    }
    user.sort_by(|a, b| a.name.to_lowercase().cmp(&b.name.to_lowercase()));
    out.extend(user);
    Ok(out)
}

/// Save (or overwrite — that's the "update" path) a user preset as one
/// pretty-printed JSON file.
pub fn save_preset(dir: &Path, name: &str, adjustments: &Adjustments) -> anyhow::Result<()> {
    let name = validate_name(name)?;
    fs::create_dir_all(dir).with_context(|| format!("creating {}", dir.display()))?;
    let file = PresetFile {
        version: PRESET_VERSION,
        name: name.clone(),
        adjustments: adjustments.clone(),
    };
    let path = dir.join(file_name_for(&name));
    let json = serde_json::to_string_pretty(&file)?;
    fs::write(&path, json).with_context(|| format!("writing {}", path.display()))?;
    Ok(())
}

/// Delete a user preset by name. Built-ins are refused.
pub fn delete_preset(dir: &Path, name: &str) -> anyhow::Result<()> {
    if is_builtin_name(name) {
        bail!("built-in presets can't be deleted");
    }
    let path = dir.join(file_name_for(name));
    if !path.is_file() {
        bail!("no user preset named \"{}\"", name.trim());
    }
    fs::remove_file(&path).with_context(|| format!("deleting {}", path.display()))?;
    Ok(())
}

/// Rename a user preset, updating both the JSON `name` field and the file
/// name. Built-ins can't be renamed; the target name must be free.
pub fn rename_preset(dir: &Path, old_name: &str, new_name: &str) -> anyhow::Result<()> {
    if is_builtin_name(old_name) {
        bail!("built-in presets can't be renamed");
    }
    let new_name = validate_name(new_name)?;
    let old_path = dir.join(file_name_for(old_name));
    if !old_path.is_file() {
        bail!("no user preset named \"{}\"", old_name.trim());
    }
    let new_path = dir.join(file_name_for(&new_name));
    // Same file is fine (display-name-only change, e.g. "a b" → "a_b" collision).
    if new_path != old_path && new_path.exists() {
        bail!("a preset named \"{new_name}\" already exists");
    }

    let text = fs::read_to_string(&old_path)
        .with_context(|| format!("reading {}", old_path.display()))?;
    let mut file: PresetFile = serde_json::from_str(&text)
        .with_context(|| format!("parsing {}", old_path.display()))?;
    file.name = new_name;
    fs::write(&new_path, serde_json::to_string_pretty(&file)?)
        .with_context(|| format!("writing {}", new_path.display()))?;
    if new_path != old_path {
        fs::remove_file(&old_path)
            .with_context(|| format!("deleting {}", old_path.display()))?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    /// Per-test temp preset dir that cleans up on drop (no tempfile dep).
    /// Tests run in parallel, so each gets its own tag-keyed directory.
    struct TempStore(PathBuf);

    impl TempStore {
        fn new(tag: &str) -> Self {
            let dir = std::env::temp_dir()
                .join(format!("pixagram_presets_{tag}_{}", std::process::id()));
            let _ = fs::remove_dir_all(&dir);
            fs::create_dir_all(&dir).unwrap();
            Self(dir)
        }
        fn path(&self) -> &Path {
            &self.0
        }
    }

    impl Drop for TempStore {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    fn sample_adjustments() -> Adjustments {
        Adjustments {
            exposure: 0.7,
            contrast: -0.2,
            saturation: 0.15,
            curve: vec![
                CurvePoint { x: 0.0, y: 0.05 },
                CurvePoint { x: 0.5, y: 0.6 },
                CurvePoint { x: 1.0, y: 1.0 },
            ],
            ..Default::default()
        }
    }

    #[test]
    fn save_then_list_round_trips() {
        let store = TempStore::new("roundtrip");
        let adj = sample_adjustments();
        save_preset(store.path(), "My Look", &adj).unwrap();

        let all = list_presets(store.path()).unwrap();
        let saved = all.iter().find(|p| p.name == "My Look").expect("listed");
        assert!(!saved.builtin);
        assert_eq!(saved.adjustments, adj, "adjustments must survive the disk round-trip");
    }

    #[test]
    fn builtins_are_always_listed_and_flagged() {
        let store = TempStore::new("builtins");
        let all = list_presets(store.path()).unwrap();
        assert!(all.len() >= 4, "expected the shipped built-ins");
        assert!(all.iter().any(|p| p.name == "Neutral"));
        assert!(all.iter().all(|p| p.builtin), "empty store lists only built-ins");
        // Built-ins first, in fixed order.
        assert_eq!(all[0].name, "Neutral");
    }

    #[test]
    fn user_presets_sort_after_builtins_by_name() {
        let store = TempStore::new("sorting");
        save_preset(store.path(), "zeta", &Adjustments::default()).unwrap();
        save_preset(store.path(), "Alpha", &Adjustments::default()).unwrap();
        let all = list_presets(store.path()).unwrap();
        let user: Vec<_> = all.iter().filter(|p| !p.builtin).map(|p| p.name.as_str()).collect();
        assert_eq!(user, vec!["Alpha", "zeta"], "case-insensitive name sort");
    }

    #[test]
    fn delete_removes_user_presets_and_refuses_builtins() {
        let store = TempStore::new("delete");
        save_preset(store.path(), "Doomed", &Adjustments::default()).unwrap();
        delete_preset(store.path(), "Doomed").unwrap();
        assert!(!list_presets(store.path()).unwrap().iter().any(|p| p.name == "Doomed"));

        assert!(delete_preset(store.path(), "Doomed").is_err(), "double delete errors");
        assert!(delete_preset(store.path(), "Neutral").is_err(), "built-ins are protected");
    }

    #[test]
    fn rename_moves_file_and_display_name() {
        let store = TempStore::new("rename");
        let adj = sample_adjustments();
        save_preset(store.path(), "Old Name", &adj).unwrap();
        save_preset(store.path(), "Taken", &Adjustments::default()).unwrap();

        rename_preset(store.path(), "Old Name", "New Name").unwrap();
        let all = list_presets(store.path()).unwrap();
        assert!(!all.iter().any(|p| p.name == "Old Name"));
        let renamed = all.iter().find(|p| p.name == "New Name").expect("renamed");
        assert_eq!(renamed.adjustments, adj, "rename must not touch the adjustments");

        assert!(
            rename_preset(store.path(), "New Name", "Taken").is_err(),
            "renaming onto an existing preset errors"
        );
        assert!(
            rename_preset(store.path(), "Neutral", "Whatever").is_err(),
            "built-ins can't be renamed"
        );
    }

    #[test]
    fn rejects_empty_and_builtin_shadowing_names() {
        let store = TempStore::new("names");
        let adj = Adjustments::default();
        assert!(save_preset(store.path(), "   ", &adj).is_err(), "empty name");
        assert!(save_preset(store.path(), "Neutral", &adj).is_err(), "shadows a built-in");
        assert!(save_preset(store.path(), "neutral", &adj).is_err(), "case-insensitive shadow");
        // Slashes and dots are sanitized out of the file name, not rejected.
        save_preset(store.path(), "a/b..c", &adj).unwrap();
        assert!(store.path().join("a_b__c.json").is_file(), "sanitized file name");
    }

    #[test]
    fn old_preset_json_with_missing_fields_still_loads() {
        // Constraint #1 carry-forward: presets written before a slider existed
        // must keep loading. Simulate one with a partial adjustments object.
        let store = TempStore::new("compat");
        fs::write(
            store.path().join("Faded.json"),
            r#"{ "version": 1, "name": "Faded", "adjustments": { "exposure": 0.5 } }"#,
        )
        .unwrap();
        let all = list_presets(store.path()).unwrap();
        let p = all.iter().find(|p| p.name == "Faded").expect("partial JSON loads");
        assert!((p.adjustments.exposure - 0.5).abs() < 1e-6);
        assert_eq!(p.adjustments.contrast, 0.0, "missing fields take defaults");
        assert_eq!(p.adjustments.hsl.len(), 8, "hsl defaults to 8 neutral bands");
    }
}
